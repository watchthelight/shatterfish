package org.shatterfish.codex;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The docs site's page of lore claims (story 7.7), built from the files under {@code lore/} and
 * compared with the committed page by {@code LoreDocsTest}, the way the Codex pages are: a hand
 * edit, or a claim added without the page rebuilt, fails the build naming the command.
 *
 * <p>{@code ./gradlew :codex:lore --args=docs} writes {@code docs/lore/index.md}.
 */
final class LoreDocs {

    private LoreDocs() {
    }

    /** The page, relative to the repository root. */
    static final String PAGE = "docs/lore/index.md";

    /** The tiers in the order a reader wants them, with what each one means. */
    private static final Map<String, String> TIERS = new TreeMap<>(Comparator.comparingInt((String t) -> "123F".indexOf(t)));

    static {
        TIERS.put("1", "Tier 1: the code confirms it");
        TIERS.put("2", "Tier 2: the harness confirms it");
        TIERS.put("3", "Tier 3: not settled by the code");
        TIERS.put("F", "Tier F: the code contradicts it");
    }

    /** The characters of a claim kept in a table cell before it is cut at a word. */
    private static final int CELL = 140;

    /** The page for the claims under {@code loreDir}. Every claim file has to parse. */
    static String render(Path loreDir) {
        List<Lore.Doc> docs = new ArrayList<>();
        for (Path file : Lore.files(loreDir)) {
            if (!LoreCheck.isClaimPath(loreDir, file)) {
                continue;
            }
            try {
                docs.add(Lore.parse(file.getFileName().toString(), Lore.read(file)));
            } catch (Lore.Unreadable bad) {
                throw new IllegalStateException(file + ": " + bad.getMessage());
            }
        }
        docs.sort(Comparator.comparing((Lore.Doc d) -> d.get("topic")).thenComparing(d -> d.get("group"))
                .thenComparingInt(d -> Lore.number(d.get("id"))));
        Map<String, List<Lore.Doc>> byTopic = new TreeMap<>();
        for (Lore.Doc doc : docs) {
            byTopic.computeIfAbsent(doc.get("topic"), t -> new ArrayList<>()).add(doc);
        }
        StringBuilder out = new StringBuilder();
        out.append("# Lore claims\n\n");
        out.append("<!-- Generated by `./gradlew :codex:lore --args=docs` from the files under lore/. Do not edit;\n")
                .append("     LoreDocsTest fails the build when this page and the files disagree. -->\n\n");
        out.append("Community knowledge enters the project as one file per claim under `lore/<topic>/<id>.md`, with\n")
                .append("its source, its variant, the version it names and the Tier the pinned code gives it\n")
                .append("([ADR-0021](../adr/0021-lore-claim-format.md)). A claim is never a mechanic by itself: only a\n")
                .append("heuristic that cites it, or a Rule that settles it, puts it into play. A claim is checked on\n")
                .append("every build by `LoreCheck`.\n\n");
        out.append("Tier 1: the code confirms it. Tier 2: the harness confirms it. Tier 3: not settled by the code,\n")
                .append("a hypothesis for the Rig. Tier F: the code contradicts it. A claim marked `needs-review` was\n")
                .append("graded at an older tag and a line it cites reads differently at the pin.\n\n");
        out.append("## Count by topic and Tier\n\n");
        out.append("| Topic | Group | Tier 1 | Tier 2 | Tier 3 | Tier F | Claims | Needs review |\n");
        out.append("|---|---|---:|---:|---:|---:|---:|---:|\n");
        for (Map.Entry<String, List<Lore.Doc>> topic : byTopic.entrySet()) {
            Map<String, List<Lore.Doc>> groups = new TreeMap<>();
            for (Lore.Doc doc : topic.getValue()) {
                groups.computeIfAbsent(doc.get("group"), g -> new ArrayList<>()).add(doc);
            }
            for (Map.Entry<String, List<Lore.Doc>> group : groups.entrySet()) {
                row(out, topic.getKey(), group.getKey(), group.getValue());
            }
            row(out, "**" + topic.getKey() + "**", "**all**", topic.getValue());
        }
        row(out, "**all**", "", docs);
        out.append('\n');
        for (Map.Entry<String, List<Lore.Doc>> topic : byTopic.entrySet()) {
            out.append("## ").append(topic.getKey()).append("\n\n");
            for (Map.Entry<String, String> tier : TIERS.entrySet()) {
                List<Lore.Doc> here = topic.getValue().stream().filter(d -> d.get("tier").equals(tier.getKey())).toList();
                if (here.isEmpty()) {
                    continue;
                }
                out.append("### ").append(tier.getValue()).append(" (").append(here.size()).append(")\n\n");
                out.append("| Claim | Subject | Variant | Status | What it says | Source |\n");
                out.append("|---|---|---|---|---|---|\n");
                for (Lore.Doc doc : here) {
                    out.append("| `").append(doc.get("id")).append("` | ")
                            .append(cell(doc.get("subject") == null ? "" : doc.get("subject"))).append(" | ")
                            .append(doc.get("variant")).append(" | ")
                            .append(doc.get("status")).append(" | ")
                            .append(cell(shorten(doc.get("claim")))).append(" | ")
                            .append('[').append(doc.get("source_type")).append("](").append(doc.get("source_url")).append(") |\n");
                }
                out.append('\n');
            }
        }
        return out.toString().stripTrailing() + "\n";
    }

    private static void row(StringBuilder out, String topic, String group, List<Lore.Doc> docs) {
        out.append("| ").append(topic).append(" | ").append(group);
        for (String tier : TIERS.keySet()) {
            out.append(" | ").append(docs.stream().filter(d -> d.get("tier").equals(tier)).count());
        }
        out.append(" | ").append(docs.size()).append(" | ")
                .append(docs.stream().filter(d -> d.get("status").equals("needs-review")).count()).append(" |\n");
    }

    /** The claim cut at a word at most {@link #CELL} characters in. */
    private static String shorten(String claim) {
        String one = claim.replaceAll("\\s+", " ").strip();
        if (one.length() <= CELL) {
            return one;
        }
        int cut = one.lastIndexOf(' ', CELL);
        return one.substring(0, cut > CELL / 2 ? cut : CELL).stripTrailing() + "…";
    }

    /** Text as a Markdown table cell: nothing in it is markup or ends the cell. */
    private static String cell(String text) {
        StringBuilder out = new StringBuilder();
        for (char c : text.toCharArray()) {
            switch (c) {
                case '|', '\\', '*', '_', '`', '[', ']', '<', '>' -> out.append('\\').append(c);
                default -> out.append(c);
            }
        }
        return out.toString();
    }
}
