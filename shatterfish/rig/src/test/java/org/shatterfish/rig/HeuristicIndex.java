package org.shatterfish.rig;

import org.shatterfish.brain.Brain;
import org.shatterfish.brain.Heuristic;

import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.Enumeration;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * What {@link HeuristicLinkTest} checks and what it writes on the Brain's Rules index (story 7.1,
 * FR-18): the {@link Heuristic} fields found by reflection over the {@code brain} classes, the two
 * kinds of row a slug may name, and the table the index carries between two markers, which the
 * test renders afresh and compares with the page the way the Codex is compared with its sources.
 *
 * <p>The table is regenerated, never hand-edited: run the test with the environment variable
 * {@value #WRITE} set to 1 and it rewrites the block.
 */
final class HeuristicIndex {

    /** The environment variable that makes the test rewrite the generated block instead of failing on it. */
    static final String WRITE = "SHATTERFISH_WRITE_HEURISTICS";

    static final String BEGIN = "<!-- heuristics:begin (generated by HeuristicLinkTest; do not edit by hand) -->";
    static final String END = "<!-- heuristics:end -->";

    static final Path INDEX = SeedSetsTest.ROOT.resolve("docs/brain-rules.md");

    /** A heuristic as the code declares it: where, and the slug it carries. */
    record Found(String owner, String field, String slug, String policy) {

        /** The constant's name as the test and the table give it. */
        String constant() {
            return owner + "." + field;
        }
    }

    /** A measured-heuristic row of the index: a slug, the page that played the value, and its Tier. */
    record Measured(String slug, String evidence, String tier, String test) {
    }

    /**
     * A Lore claim (story 7.7): its id is the file stem of {@code lore/<topic>/<id>.md}, its Tier and
     * the {@code policy:}, {@code rule:} and {@code playbook:} targets of its {@code implemented_in}.
     */
    record LoreClaim(String id, String tier, List<String> implementedIn) {
    }

    private static final Pattern RULE_KEY = Pattern.compile("^\\| <a id=\"([^\"]+)\"></a>`([^`]+)` \\|.*");
    private static final Pattern RULE_LINK = Pattern.compile("\\[([a-z-]+): \"([^\"]+)\"\\]\\(rules/([a-z-]+)\\.md\\)");
    private static final Pattern MEASURED_ROW = Pattern.compile("^\\| `([a-z0-9-]+)` \\| \\[[^\\]]+\\]\\(([^)]+)\\) \\| ([23]) \\| ([^|]+) \\|$");

    private static final String PACKAGE = Brain.class.getPackageName();

    private HeuristicIndex() {
    }

    // ---- the code side -----------------------------------------------------------------------

    /** Every class of the {@code brain} module's main output, loaded without running initializers. */
    static List<Class<?>> brainClasses() {
        List<String> names = new ArrayList<>();
        try {
            Path location = Path.of(Brain.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            if (Files.isDirectory(location)) {
                try (Stream<Path> walk = Files.walk(location)) {
                    walk.filter(file -> file.toString().endsWith(".class")).forEach(file -> names.add(
                            location.relativize(file).toString().replace('\\', '/')));
                }
            } else {
                try (JarFile jar = new JarFile(location.toFile())) {
                    Enumeration<JarEntry> entries = jar.entries();
                    while (entries.hasMoreElements()) {
                        String name = entries.nextElement().getName();
                        if (name.endsWith(".class")) {
                            names.add(name);
                        }
                    }
                }
            }
        } catch (IOException | URISyntaxException e) {
            throw new IllegalStateException("cannot list the brain classes", e);
        }
        List<Class<?>> classes = new ArrayList<>();
        for (String name : names) {
            String binary = name.substring(0, name.length() - ".class".length()).replace('/', '.');
            if (!binary.startsWith(PACKAGE + ".") || binary.endsWith("module-info") || binary.endsWith("package-info")) {
                continue;
            }
            try {
                classes.add(Class.forName(binary, false, Brain.class.getClassLoader()));
            } catch (ClassNotFoundException | LinkageError e) {
                throw new IllegalStateException("cannot load " + binary, e);
            }
        }
        classes.sort(Comparator.comparing(Class::getName));
        return classes;
    }

    /** A class's name as the table gives it: the nested classes joined with dots, without the package. */
    static String shortName(Class<?> type) {
        return type.getName().substring(PACKAGE.length() + 1).replace('$', '.');
    }

    /** The heuristics declared in code, sorted by slug and then by constant. */
    static List<Found> annotated() {
        List<Found> found = new ArrayList<>();
        for (Class<?> type : brainClasses()) {
            for (Field field : type.getDeclaredFields()) {
                Heuristic heuristic = field.getAnnotation(Heuristic.class);
                if (heuristic != null) {
                    found.add(new Found(shortName(type), field.getName(), heuristic.value(), policyOf(type)));
                }
            }
        }
        found.sort(Comparator.comparing(Found::slug).thenComparing(Found::constant));
        return found;
    }

    /** The numeric constants the brain classes declare, as {@code Class.FIELD}, annotated or not. */
    static List<String> numericConstants() {
        List<String> constants = new ArrayList<>();
        for (Class<?> type : brainClasses()) {
            for (Field field : type.getDeclaredFields()) {
                int modifiers = field.getModifiers();
                Class<?> kind = field.getType();
                boolean numeric = kind == int.class || kind == long.class || kind == double.class || kind == float.class
                        || kind == short.class || kind == byte.class;
                if (numeric && Modifier.isStatic(modifiers) && Modifier.isFinal(modifiers) && !field.isSynthetic()
                        && !field.getName().equals("serialVersionUID")) {
                    constants.add(shortName(type) + "." + field.getName());
                }
            }
        }
        constants.sort(Comparator.naturalOrder());
        return constants;
    }

    /** The Policy a class belongs to: its own name when it is a Policy the Brain arbitrates, else the class. */
    private static String policyOf(Class<?> type) {
        Class<?> top = type;
        while (top.getEnclosingClass() != null) {
            top = top.getEnclosingClass();
        }
        try {
            Field name = top.getDeclaredField("NAME");
            name.setAccessible(true);
            if (Modifier.isStatic(name.getModifiers()) && name.get(null) instanceof String policy
                    && Brain.policyNames().contains(policy)) {
                return policy;
            }
        } catch (NoSuchFieldException | IllegalAccessException e) {
            // not a Policy: the class stands for itself
        }
        return shortName(top);
    }

    // ---- the page side -----------------------------------------------------------------------

    static List<String> lines() throws IOException {
        return Files.readAllLines(INDEX, StandardCharsets.UTF_8);
    }

    /** Each Rule row's slug and the Tier of the Rule it links, read from the Rule's own page. */
    static Map<String, String> ruleTiers() throws IOException {
        Map<String, String> tiers = new TreeMap<>();
        for (String line : lines()) {
            Matcher key = RULE_KEY.matcher(line);
            if (!key.matches()) {
                continue;
            }
            Matcher rule = RULE_LINK.matcher(line);
            if (!rule.find()) {
                throw new AssertionError("a row links no Rule: " + line);
            }
            Path page = SeedSetsTest.ROOT.resolve("docs/rules/" + rule.group(3) + ".md");
            Optional<String> row = Files.readAllLines(page, StandardCharsets.UTF_8).stream()
                    .filter(candidate -> candidate.startsWith("| " + rule.group(2))).findFirst();
            String[] cells = row.orElseThrow(() -> new AssertionError("no Rule row opens with " + rule.group(2))).split("\\|");
            tiers.put(key.group(2), cells[cells.length - 2].strip());
        }
        return tiers;
    }

    /** Every Lore claim under {@code lore/<topic>/}, by id (the file stem). */
    static Map<String, LoreClaim> loreClaims() throws IOException {
        Map<String, LoreClaim> claims = new TreeMap<>();
        Path lore = SeedSetsTest.ROOT.resolve("lore");
        if (!Files.isDirectory(lore)) {
            return claims;
        }
        List<Path> files;
        try (Stream<Path> walk = Files.walk(lore, 2)) {
            files = walk.filter(f -> f.getNameCount() - lore.getNameCount() == 2 && f.toString().endsWith(".md")).sorted().toList();
        }
        for (Path file : files) {
            String id = file.getFileName().toString().replaceFirst("\\.md$", "");
            String tier = "?";
            List<String> implemented = new ArrayList<>();
            boolean inList = false;
            List<String> lines = Files.readAllLines(file, StandardCharsets.UTF_8);
            for (int i = 1; i < lines.size() && !lines.get(i).equals("---"); i++) {
                String line = lines.get(i);
                if (line.startsWith("tier:")) {
                    tier = line.substring(5).strip();
                }
                if (line.startsWith("implemented_in:")) {
                    inList = true;
                    continue;
                }
                if (inList && line.startsWith("  - ")) {
                    implemented.add(line.substring(4).strip());
                } else if (!line.startsWith(" ")) {
                    inList = false;
                }
            }
            claims.put(id, new LoreClaim(id, tier, implemented));
        }
        return claims;
    }

    /** The measured-heuristic rows of the index, by slug. */
    static Map<String, Measured> measured() throws IOException {
        Map<String, Measured> rows = new TreeMap<>();
        for (String line : lines()) {
            Matcher row = MEASURED_ROW.matcher(line);
            if (row.matches()) {
                Measured measured = new Measured(row.group(1), row.group(2), row.group(3), row.group(4).strip());
                if (rows.put(measured.slug(), measured) != null) {
                    throw new AssertionError("a measured-heuristic slug names one row only: " + measured.slug());
                }
            }
        }
        return rows;
    }

    /** The block the page should carry between its markers, for these heuristics. */
    static String render(List<Found> found, Map<String, String> rules, Map<String, Measured> measured,
                         Map<String, LoreClaim> lore) {
        int ruleLinked = 0;
        int measuredLinked = 0;
        int loreLinked = 0;
        int unlinked = 0;
        StringBuilder table = new StringBuilder();
        table.append("| Constant | Slug | Linked to | Tier | Policies |\n|---|---|---|---|---|\n");
        for (Found heuristic : found) {
            String linked;
            String tier;
            if (heuristic.slug().equals(Heuristic.UNLINKED)) {
                linked = "unlinked";
                tier = "-";
                unlinked++;
            } else if (rules.containsKey(heuristic.slug())) {
                linked = "Rule [`" + heuristic.slug() + "`](#" + heuristic.slug() + ")";
                tier = rules.get(heuristic.slug());
                ruleLinked++;
            } else if (lore.containsKey(heuristic.slug())) {
                linked = "Lore `" + heuristic.slug() + "`";
                tier = lore.get(heuristic.slug()).tier();
                loreLinked++;
            } else {
                Measured row = measured.get(heuristic.slug());
                linked = "[`" + heuristic.slug() + "`](" + (row == null ? "" : row.evidence()) + ")";
                tier = row == null ? "?" : row.tier();
                measuredLinked++;
            }
            table.append("| `").append(heuristic.constant()).append("` | `").append(heuristic.slug()).append("` | ")
                    .append(linked).append(" | ").append(tier).append(" | `").append(heuristic.policy()).append("` |\n");
        }
        return "Heuristics found: " + found.size() + ". Linked to a Rule: " + ruleLinked + ". Linked to a Lore claim: " + loreLinked + ". Linked to a measurement (Tier 3 unless the row says 2): "
                + measuredLinked + ". Unlinked: " + unlinked + ".\n\n" + table;
    }

    /** The block now on the page between the markers, or empty if the markers are missing. */
    static Optional<String> block() throws IOException {
        String text = Files.readString(INDEX, StandardCharsets.UTF_8);
        int begin = text.indexOf(BEGIN);
        int end = text.indexOf(END);
        if (begin < 0 || end < begin) {
            return Optional.empty();
        }
        return Optional.of(text.substring(begin + BEGIN.length(), end).strip() + "\n");
    }

    /** Replaces the block between the markers with {@code rendered}. */
    static void write(String rendered) throws IOException {
        String text = Files.readString(INDEX, StandardCharsets.UTF_8);
        int begin = text.indexOf(BEGIN);
        int end = text.indexOf(END);
        if (begin < 0 || end < begin) {
            throw new AssertionError("the index has no heuristics markers");
        }
        Files.writeString(INDEX, text.substring(0, begin + BEGIN.length()) + "\n\n" + rendered + "\n" + text.substring(end),
                StandardCharsets.UTF_8);
    }
}
